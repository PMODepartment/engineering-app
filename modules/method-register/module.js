        'Replace the existing register for this project</label>' +
        '<div class="pd-modal-actions"><button class="pd-btn" id="mr-imp-cancel">Cancel</button>' +
        '<button class="pd-btn pd-btn-primary" id="mr-imp-go">Import</button></div>';
