  async function load() {
    var host = document.getElementById('mr-view');
    host.innerHTML = skeletonHTML();
    // Keyset-paginated: PostgREST caps a select at 1000 rows and returns no
    // error, and this register runs to ~530 rows per project already.
    var out = [], last = null;
    try {
      for (var i = 0; i < 40; i++) {
        var q = sb().from(TABLE).select('*').eq('project_id', pid).order('id').limit(1000);
        if (last) q = q.gt('id', last);
        var res = await q;
        if (res.error) throw res.error;
        var batch = res.data || [];
        out = out.concat(batch);
        if (batch.length < 1000) break;
        last = batch[batch.length - 1].id;
      }
    } catch (e) {
      host.innerHTML = '<div class="pd-card mr-empty"><h3>Could not load the register</h3><p>' +
        esc(e.message || e) + '</p><p class="mr-mut">If the table is missing, run ' +
        '<code>migrations/0013-method-register.sql</code>.</p></div>';
      return;
    }
    // Display order: sort_order, then the workbook's own numeric seq_no.
    rows = out.sort(function (a, b) {
      var sa = a.sort_order == null ? 1e9 : a.sort_order, sbb = b.sort_order == null ? 1e9 : b.sort_order;
      if (sa !== sbb) return sa - sbb;
      return String(a.seq_no || '').localeCompare(String(b.seq_no || ''), undefined, { numeric: true });
    });
    syncFilterOptions();
    render();
  }

