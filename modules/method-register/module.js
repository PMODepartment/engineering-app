  function normStatus(v) {
    var s = String(v == null ? '' : v).trim();
    if (!s || s === '-') return null;
    var k = LEGACY_STATUS[s.toLowerCase()];
    if (k !== undefined) return k || null;
    var lo = s.toLowerCase();
    if (lo === 'approved') return 'Approved';
    if (lo.indexOf('comment') !== -1) return 'Approved w/ Comments';
    if (lo.indexOf('disappr') !== -1) return 'Disapproved';
    if (lo === 'open') return 'Open';
    return s;
  }
  function normBall(v) {
    var s = String(v == null ? '' : v).trim().toLowerCase();
    if (!s || s === '-') return null;
    if (s === 'engg' || s === 'eng' || s === 'engineering') return 'Engg';
    if (s === 'ops') return 'Ops';
    if (s === 'closed') return 'Closed';
    if (s === 'open') return 'Open';
    return String(v).trim();
  }

  function parseWorkbook(wb) {
    // The registry sheet is the one whose row 8-ish header carries "Method
    // Statement Title"; rank by how many method statements it yields.
    var best = null;
    wb.SheetNames.forEach(function (nm) {
      var g = gridOf(wb.Sheets[nm]);
      var hdr = -1;
      for (var i = 0; i < Math.min(g.length, 40); i++) {
        var joined = g[i].join('|').toLowerCase();
        if (joined.indexOf('method statement title') !== -1) { hdr = i; break; }
      }
      if (hdr < 0) return;
      var recs = parseGrid(g, hdr);
      if (!best || recs.items > best.items) best = { sheet: nm, hdr: hdr, grid: g, recs: recs.records, items: recs.items };
    });
    return best;
  }

  function parseGrid(g, hdr) {
    var out = [], items = 0, order = 0;
    var curTrade = null, curTradeName = null, curGroup = null, curSub = null;
    for (var i = hdr + 1; i < g.length; i++) {
      var row = g[i];
      var t1 = row[COL.t1] || '', t2 = row[COL.t2] || '', t3 = row[COL.t3] || '', t4 = row[COL.t4] || '';
      var code = (row[COL.trade] || '').trim(), no = (row[COL.no] || '').trim();
      if (!t1 && !t2 && !t3 && !t4) continue;

      if (t1) {                                   // trade header
        curTrade = code || null; curTradeName = t1.replace(/\s+/g, ' ').trim();
        curGroup = curSub = null;
        out.push({ node_kind: 'trade', trade_code: curTrade, trade_name: curTradeName,
          seq_no: no || null, title: curTradeName, counts: false, sort_order: order++ });
        continue;
      }
      if (t2) {                                   // group
        curGroup = t2.replace(/\s+/g, ' ').trim(); curSub = null;
        out.push({ node_kind: 'group', trade_code: curTrade, trade_name: curTradeName,
          group_name: curGroup, seq_no: no || null, title: curGroup, counts: false, sort_order: order++ });
        continue;
      }
      if (t3) {                                   // sub-group
        curSub = t3.replace(/\s+/g, ' ').trim();
        out.push({ node_kind: 'subgroup', trade_code: curTrade, trade_name: curTradeName,
          group_name: curGroup, subgroup_name: curSub, seq_no: no || null,
          title: curSub, counts: false, sort_order: order++ });
        continue;
      }
      // a method statement
      var nRaw = String(row[COL.n] == null ? '' : row[COL.n]).trim();
      var subs = [];
      [[COL.rev1p, COL.rev1a], [COL.rev2p, COL.rev2a], [COL.rev3p, COL.rev3a], [COL.rev4p, COL.rev4a]]
        .forEach(function (pair, idx) {
          var p = realDate(parseDate(row[pair[0]])), a = realDate(parseDate(row[pair[1]]));
          if (p || a) subs.push({ rev: idx + 1, planned: p, actual: a });
        });
      items++;
      out.push({
        node_kind: null,
        trade_code: curTrade, trade_name: curTradeName,
        group_name: curGroup, subgroup_name: curSub,
        seq_no: no || null,
        ms_code: (code || (curTrade && no ? curTrade + no : null)) || null,
        title: t4.replace(/\s+/g, ' ').trim(),
        // ⚠️ N=1 is the workbook's "counts toward the target" flag.
        counts: nRaw === '1',
        latest_revision: subs.length || null,
        plan_submission_date:   realDate(parseDate(row[COL.planSub])),
        actual_submission_date: realDate(parseDate(row[COL.actSub])),
        submissions: subs,
        plan_approval_date:   realDate(parseDate(row[COL.planAppr])),
        actual_approval_date: realDate(parseDate(row[COL.actAppr])),
        status: normStatus(row[COL.status]),
        ball_in: normBall(row[COL.ballIn]),
        approved_sheets: /^\d+$/.test(String(row[COL.apprSheets] || '').trim()) ? +row[COL.apprSheets] : null,
        // 'balance' in the sheet means OUTSTANDING, so done = not balance.
        hirac_done: String(row[COL.hirac] || '').trim().toLowerCase() !== 'balance' && !!String(row[COL.hirac] || '').trim(),
        qcc_done:   String(row[COL.qcc]   || '').trim().toLowerCase() !== 'balance' && !!String(row[COL.qcc]   || '').trim(),
        mas_done:   String(row[COL.mas]   || '').trim().toLowerCase() !== 'balance' && !!String(row[COL.mas]   || '').trim(),
        isd_done:   String(row[COL.isd]   || '').trim().toLowerCase() !== 'balance' && !!String(row[COL.isd]   || '').trim(),
        reference_link: (String(row[COL.link] || '').trim().indexOf('http') === 0) ? String(row[COL.link]).trim() : null,
        priority: /^[123]$/.test(String(row[COL.priority] || '').trim()) ? +row[COL.priority] : null,
        responsible: String(row[COL.responsible] || '').trim() || null,
        target_date: realDate(parseDate(row[COL.target])),
        sort_order: order++
      });
    }
    return { records: out, items: items };
  }

