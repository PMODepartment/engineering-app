/* Method Register — modules/method-register/module.js
   Built against "MCC. ENG. MET. MRE. SLN101 Method Registry Tracker. 2026 07 15"
   (Strevi Residences). The workbook's SUMMARY sheet is generated by formulas, and
   THOSE FORMULAS ARE THE SPEC. Transcribed verbatim, per trade:

     TOTAL MS (G)   = 'Method Registry 01'!N<trade>  = SUM of N over the trade block
                      — N is 1 per counted item, so this is a COUNT of N=1 rows
     APP (V)        = COUNTIFS(code "*TW*", Status "Approved",              N=1)
     AWC (W)        = COUNTIFS(code "*TW*", Status "Approved w/ Comments",  N=1)
     DIS (X)        = COUNTIFS(code "*TW*", Status "disapproved",           N=1)
     TOTAL SUBMITTED (I) = V + W + X
     PROGRESS (J)   = I / G
     BALANCE  (K)   = G − I
     % APP    (Y)   = V / G
     HIRAC/QCC/MAS/ISD (M/O/Q/S) = SUMIFS(N, <attachment> = "Balance", code "*TW*")
       and % BAL (N/P/R/T) = that / G
     ENGG (AA) / OPS (AB)  = COUNTIFS(code "*TW*", Ball-In "engg"/"ops", N=1)

   ⚠️ `counts` (the workbook's N=1) gates EVERY metric above. The sample workbook
   holds 323 method-statement rows of which only 103 count; ignoring the flag
   over-reports the programme by 3x.

   TWO DEFECTS IN THE WORKBOOK — reproduced, proven, then fixed (both surfaced in
   the Summary's reconciliation note rather than silently corrected):

   1. ⚠️ BALL IN COURT loses most of the register. SUMMARY counts Ball-In "engg"
      and "ops", but the sheet's own vocabulary is Open / Ops / Closed / "-".
      Nobody ever types "engg", so ENGG reads 0 for every trade, and the 79
      counted items sitting at "Open" are attributed to NEITHER column: the block
      accounts for 19 of 103. `ballInCounts()` reports Engineering / Ops / Closed
      / Unassigned so the four add up to the total.
   2. ⚠️ THE TOTAL ROW AVERAGES RATIOS. J18 = AVERAGE(J6:J17) and Y18 =
      AVERAGE(Y6:Y17) — an unweighted mean over 12 trades, five of which have a
      zero target — while every other total on that row is a real SUM. The
      workbook prints 3.49% progress where the aggregate 5/103 is 4.85%.
      `totals()` aggregates; `legacyTotals()` reproduces the average PURELY for
      the reconciliation note. Never report from it. */
