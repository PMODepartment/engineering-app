  function ballOf(r) { return (r.ball_in || '').trim(); }

  // ==========================================================================
  // SUMMARY maths — the workbook's formulas, per trade
  // ==========================================================================
  function tradeStats(code) {
    var mine = rows.filter(function (r) { return counted(r) && (r.trade_code || '') === code; });
    var total = mine.length;                       // = SUM(N) over the block
    var app = 0, awc = 0, dis = 0, engg = 0, ops = 0, closed = 0, unassigned = 0;
    var bal = { hirac_done: 0, qcc_done: 0, mas_done: 0, isd_done: 0 };
    mine.forEach(function (r) {
      var s = statusOf(r);
      if (s === 'Approved') app++;
      else if (s === 'Approved w/ Comments') awc++;
      else if (s === 'Disapproved') dis++;
      var b = ballOf(r).toLowerCase();
      if (b === 'engg') engg++; else if (b === 'ops') ops++;
      else if (b === 'closed') closed++; else unassigned++;
      ATTACH.forEach(function (a) { if (!r[a[0]]) bal[a[0]]++; });
    });
    var submitted = app + awc + dis;               // I = V+W+X
    return {
      code: code, name: TRADE_NAME[code] || code, total: total,
      app: app, awc: awc, dis: dis, submitted: submitted,
      balance: total - submitted,
      progress: total ? submitted / total : 0,
      pctApp: total ? app / total : 0,
      engg: engg, ops: ops, closed: closed, unassigned: unassigned,
      bal: bal
    };
  }
  function allTradeStats() { return TRADES.map(function (t) { return tradeStats(t[0]); }); }

  // Aggregate totals — every figure is a real sum, INCLUDING the two percentages.
  function totals(st) {
    var t = { total: 0, app: 0, awc: 0, dis: 0, submitted: 0, balance: 0,
      engg: 0, ops: 0, closed: 0, unassigned: 0,
      bal: { hirac_done: 0, qcc_done: 0, mas_done: 0, isd_done: 0 } };
    st.forEach(function (s) {
      ['total','app','awc','dis','submitted','balance','engg','ops','closed','unassigned']
        .forEach(function (k) { t[k] += s[k]; });
      ATTACH.forEach(function (a) { t.bal[a[0]] += s.bal[a[0]]; });
    });
    t.progress = t.total ? t.submitted / t.total : 0;
    t.pctApp = t.total ? t.app / t.total : 0;
    return t;
  }
  // ⚠️ Reproduces the workbook's AVERAGE(J6:J17) / AVERAGE(Y6:Y17) so the
  // Summary can show WHY its own total differs. Never report from this.
  function legacyTotals(st) {
    var n = st.length || 1;
    return {
      progress: st.reduce(function (a, s) { return a + s.progress; }, 0) / n,
      pctApp:   st.reduce(function (a, s) { return a + s.pctApp; }, 0) / n
    };
  }

  // ==========================================================================
